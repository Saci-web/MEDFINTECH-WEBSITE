let currentLang = localStorage.getItem('medfintech_lang') || 'fr';

function t(key, lang = currentLang) {
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('medfintech_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.title = t('meta.title');
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = t('meta.description');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  const langSelect = document.querySelector('.lang-switch');
  if (langSelect) langSelect.value = lang;

  if (typeof window.refreshScreensI18n === 'function') window.refreshScreensI18n(lang);
}

function switchLang(lang) {
  applyLanguage(lang);
}

document.addEventListener('DOMContentLoaded', () => applyLanguage(currentLang));
